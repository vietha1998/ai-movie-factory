import re,sys
p=sys.argv[1]
txt=open(p,encoding='utf-8').read()

def add(sc, line):
    """Append line to SC block. N lines go before dialogue lines; dialogue lines go at the end."""
    global txt
    m=re.search(r'^### %s ·.*?$'%sc, txt, re.M)
    assert m, sc
    start=m.end()
    nxt=re.search(r'^(### |\[NARRATOR|\[MID-ROLL|\[Kết thúc|\[END CARD\]|## \[)', txt[start:], re.M)
    end=start+nxt.start() if nxt else len(txt)
    block=txt[start:end].rstrip('\n')
    lines=block.split('\n')
    if line.startswith('N: '):
        assert not any(l.startswith('N: ') for l in lines), sc+' already has N'
        # insert before first dialogue line (a line matching 'X: ' not ACTION/SOUND)
        idx=len(lines)
        for i,l in enumerate(lines):
            if re.match(r'^[가-힣A-Za-z ()의를]+?: ',l) and not l.startswith('N: '):
                idx=i; break
        lines.insert(idx,line)
    else:
        lines.append(line)
    txt=txt[:start]+'\n'.join(lines)+'\n\n'+txt[end:]

